import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {dirname,resolve} from 'node:path';
import {writeFileSync} from 'node:fs';
import {createServer} from 'vite';
import react from '@vitejs/plugin-react';
import {createRuntime} from './remediation/service-ui-runtime.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const runtime=createRuntime('browser');
const require=createRequire(import.meta.url);
const {chromium}=process.env.PLAYWRIGHT_MODULE ? await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href) : require('playwright');
const server=await createServer({root,cacheDir:runtime.cache,configFile:false,plugins:[react()],server:{host:'127.0.0.1',port:0}});
await server.listen();
const browser=await chromium.launch({headless:true,channel:'msedge'});
const checks=[],metrics={},errors=[];
const record=(name)=>checks.push(name);
try {
 const page=await browser.newPage({viewport:{width:1280,height:820}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:'+server.httpServer.address().port+'/scripts/fixtures/desktop-ui.html');
 await page.locator('.mission-task-entry').first().waitFor();
 const nav=page.getByRole('navigation',{name:'主导航'});
 metrics.taskHeights=await page.locator('.mission-task-entry').evaluateAll(rows=>rows.map(e=>e.getBoundingClientRect().height));
 assert.ok(metrics.taskHeights.every(h=>h<=88&&h>=72),JSON.stringify(metrics.taskHeights));
 assert.ok(await page.locator('.mission-task-entry .task-title-link').first().evaluate(e=>e.scrollWidth>e.clientWidth),'long title is contained');
 assert.ok(await page.locator('.mission-task-entry').evaluateAll(rows=>rows.every(e=>e.querySelector('.task-center-row-action').getBoundingClientRect().right<=e.getBoundingClientRect().right)),'actions remain inside rows');
 assert.ok(await page.locator('.mission-task-entry').evaluateAll(rows=>rows.filter(e=>e.getBoundingClientRect().bottom<=innerHeight).length)>=5);
 await page.screenshot({path:resolve(runtime.directory,'tasks.png')});record('compact-tasks-five-visible');
 await page.locator('.main-content').evaluate(e=>e.scrollTo(0,400));
 const scrollBefore=await page.locator('.main-content').evaluate(e=>e.scrollTop);
 assert.ok(scrollBefore>0);
 const loadsBefore=await page.evaluate(()=>window.desktopFixtureLocalLoads);
 await page.waitForFunction(before=>window.desktopFixtureLocalLoads>before,loadsBefore,{timeout:7000});
 assert.equal(await page.locator('.main-content').evaluate(e=>e.scrollTop),scrollBefore);
 record('background-refresh-preserves-scroll');
 await page.getByRole('button',{name:'桌面任务 6',exact:true}).click();
 await page.getByRole('button',{name:'返回我的任务',exact:true}).click();
 await page.waitForFunction(top=>Math.abs(document.querySelector('.main-content').scrollTop-top)<5,scrollBefore);
 record('task-detail-return-restores-scroll');
 await nav.getByRole('button',{name:'待处理',exact:true}).click();
 await page.locator('.inbox-summary').waitFor();
 assert.equal(await page.evaluate(()=>window.desktopFixtureMounts),1,'persistent conversation stays mounted across navigation');
 assert.equal(await page.locator('.main-content').evaluate(e=>e.scrollTop),0);
 metrics.summary=await page.locator('.inbox-summary').boundingBox();
 assert.ok(metrics.summary.height>=76);
 assert.equal(await page.locator('.inbox-section').count(),1);
 metrics.inboxGrid=await page.locator('.inbox-grid').boundingBox();
 assert.ok(metrics.inboxGrid.width>1000);
 assert.equal(await page.getByText('暂无操作审批。',{exact:true}).count(),0);
 await page.screenshot({path:resolve(runtime.directory,'inbox.png')});record('inbox-summary-full-width-single-group');record('primary-navigation-resets-scroll');
 await nav.getByRole('button',{name:'首页',exact:true}).click();
 assert.match(await page.locator('.overview-facts').innerText(),/工作台账号\s*已授权/);
 assert.match(await page.locator('.overview-facts').innerText(),/工作台任务\s*连接异常/);
 const title=await page.locator('.page-header h1').evaluate(e=>{const s=getComputedStyle(e);return [s.fontSize,s.fontWeight,s.lineHeight]});
 assert.deepEqual(title,['20px','600','26px']);
 assert.equal(await page.locator('.quick-access-all-button .quick-access-button-label').evaluate(e=>e.scrollWidth<=e.clientWidth),true);
 record('scoped-status-page-title-and-tool-label');
 await page.evaluate(()=>window.desktopFixture.setWorkerOnline(true));
 await page.locator('.workspace-status-panel.ready').waitFor();
 const readyStyle=()=>page.locator('.workspace-status-panel.ready,.workspace-status-icon.ready,.workspace-status-pill.ready i').evaluateAll(elements=>elements.flatMap(e=>[null,'::before','::after'].map(p=>{const s=getComputedStyle(e,p);return {animation:s.animationName,shadow:s.boxShadow}})));
 const readyBefore=await readyStyle();
 assert.ok(readyBefore.length>0&&readyBefore.every(s=>s.animation==='none'));
 await page.waitForTimeout(10000);
 assert.deepEqual(await readyStyle(),readyBefore);
 await page.screenshot({path:resolve(runtime.directory,'home-ready.png')});record('ready-state-static-for-ten-seconds');
 await nav.getByRole('button',{name:'工作流',exact:true}).click();
 await page.locator('.workflow-issue-diagnostic').first().waitFor();
 assert.equal(await page.getByText('依赖插件未响应',{exact:true}).count(),1);
 assert.equal(await page.getByText('依赖插件内容已变化',{exact:true}).count(),1);
 assert.equal(await page.getByText('工作流配置无法读取',{exact:true}).count(),1);
 await page.locator('.workflow-issue-diagnostic summary').first().click();
 assert.ok(await page.locator('.workflow-issue-diagnostic pre').first().isVisible());
 await page.screenshot({path:resolve(runtime.directory,'workflow-diagnostic.png')});
 await page.getByRole('button',{name:'检查已装插件',exact:true}).first().click();
 await page.getByRole('heading',{name:'已装插件',exact:true}).waitFor();record('workflow-error-diagnostic-and-recovery');
 await page.evaluate(()=>window.desktopFixture.setPage('ai'));
 await page.getByText('正在读取 AI 服务…',{exact:true}).waitFor();
 assert.equal(await page.getByText('还没有可用的 AI 服务',{exact:true}).count(),0);
 assert.equal(await page.getByText('工作台 AI 服务不可用',{exact:true}).count(),0);
 await page.screenshot({path:resolve(runtime.directory,'ai-loading.png')});
 await page.evaluate(()=>window.desktopFixture.setAiState('error'));
 await page.getByText('AI 服务读取失败',{exact:true}).waitFor();
 await page.getByRole('button',{name:'重试',exact:true}).click();
 await page.getByText('正在读取 AI 服务…',{exact:true}).waitFor();
 await page.evaluate(()=>window.desktopFixture.setAiState('empty'));
 await page.getByText('尚未配置本机 AI 服务',{exact:true}).waitFor();record('ai-loading-error-retry-empty-distinct');
 assert.deepEqual(errors,[]);
 writeFileSync(resolve(runtime.directory,'result.json'),JSON.stringify({passed:true,checks,metrics,errors},null,2));
 console.log(JSON.stringify({passed:true,checks,metrics,evidence:runtime.directory}));
} catch(error){await pageFailure(browser,runtime,error);throw error;}
finally{await browser.close();await server.close();}
async function pageFailure(browser,runtime,error){const page=browser.contexts()[0]?.pages()[0];if(page)await page.screenshot({path:resolve(runtime.directory,'failure.png')});writeFileSync(resolve(runtime.directory,'failure.txt'),String(error)+'\n'+JSON.stringify(errors));}
